  await page.context().clearCookies();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:4179/');
  await page.locator('.role-administrator').click();
  await page.getByLabel('Email address').fill('admin@browser.test');
  await page.getByLabel('Password', { exact: true }).fill('BrowserTest2026!');
  await page.getByRole('button', { name: 'Sign in & keep learning' }).click();
  await page.locator('.workspace-header h1').waitFor();
  await page.route('**/api/admin/modules', route => route.request().method() === 'GET' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Module list temporarily unavailable.' }) }) : route.continue());
  await page.getByRole('button', { name: 'Manage Content', exact: true }).click();
  await page.getByText('Module list temporarily unavailable.', { exact: true }).waitFor();
  await page.unroute('**/api/admin/modules');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByRole('heading', { name: 'Edit module', exact: true }).waitFor();
